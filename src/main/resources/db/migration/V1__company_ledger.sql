-- Supports both an empty database and the existing Budget Tracker schema.
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL
);
ALTER TABLE users ADD COLUMN IF NOT EXISTS role VARCHAR(30) NOT NULL DEFAULT 'VIEWER';
-- One-time conversion: the oldest existing account becomes the company administrator.
UPDATE users SET role = 'ADMIN'
WHERE id = (SELECT MIN(id) FROM users)
AND NOT EXISTS (SELECT 1 FROM users WHERE role = 'ADMIN');

CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    type VARCHAR(255) NOT NULL CHECK (type IN ('INCOME','EXPENSE'))
);
CREATE TABLE IF NOT EXISTS counterparties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    tax_number VARCHAR(20), email VARCHAR(200), phone VARCHAR(30), kind VARCHAR(20) NOT NULL
);
CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(255) NOT NULL CHECK (type IN ('INCOME','EXPENSE')),
    amount NUMERIC(12,2) NOT NULL,
    date DATE NOT NULL, description VARCHAR(1000),
    user_id BIGINT NOT NULL REFERENCES users(id),
    category_id BIGINT NOT NULL REFERENCES categories(id)
);
ALTER TABLE transactions ALTER COLUMN description TYPE VARCHAR(1000);
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS counterparty_id BIGINT REFERENCES counterparties(id);
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS document_number VARCHAR(80);
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS department VARCHAR(100);
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS due_date DATE;
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS payment_status VARCHAR(30) NOT NULL DEFAULT 'PAID';
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS cancelled BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS cancellation_reason VARCHAR(500);
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS updated_by VARCHAR(255);
ALTER TABLE transactions ADD CONSTRAINT ck_transaction_amount CHECK (amount > 0);
ALTER TABLE transactions ADD CONSTRAINT ck_payment_status CHECK (payment_status IN ('PAID','PENDING'));

CREATE TABLE audit_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    actor VARCHAR(255) NOT NULL, action VARCHAR(255) NOT NULL,
    entity_type VARCHAR(255) NOT NULL, entity_id BIGINT,
    before_value TEXT, after_value TEXT
);
CREATE INDEX idx_transactions_date ON transactions(date DESC, id DESC);
CREATE INDEX idx_transactions_party ON transactions(counterparty_id);
CREATE INDEX idx_transactions_category ON transactions(category_id);
CREATE INDEX idx_transactions_status ON transactions(payment_status, due_date) WHERE cancelled = FALSE;
CREATE INDEX idx_audit_date ON audit_entries(occurred_at DESC);

